def _sanitize_content(content: str) -> str:
    """Удалить служебные теги DM из пользовательского ввода (анти-чит)."""
    return _TAG_RE.sub("", content)


def _strip_prompt_leak(reply: str) -> str:
    """Вырезать строки, где модель процитировала правила системного промпта.

    flash-модель иногда вставляет в ответ игроку служебные инструкции:
    «Первая строка ответа будет с локацией...», «тег [STATE] не показывай»,
    «ОБЯЗАТЕЛЬНЫЙ ФОРМАТ ОТВЕТА» и т.п. Это утечка промпта — игрок видит
    правила форматирования вместо игрового текста. Удаляем такие строки
    целиком (вместе с обёртками вроде «=== ... ===»).
    """
    import re as _re

    leak_patterns = [
        # Прямые цитаты блоков формата из system prompt
        r"первая строка\s+ответа",
        r"вторая строка\s+[—\-–]\s+атмосферн",
        r"третья строка\s+[—\-–]\s+тег",
        r"первая строка\s+всегда",
        r"последняя строка\s+всегда",
        r"обязательный формат ответа",
        r"нарушение\s*=\s*ошибка",
        r"формат ответа",
        # Инструкции про теги, обращённые к модели
        r"тег\s+\[STATE\]\s+не\s+показывай",
        r"в\s+ответе\s+игроку\s+тег\s+не\s+показывай",
        r"тег\s+не\s+показывай",
        r"не\s+говори\s+игроку",
        r"обрабатывается\s+автоматически",
        r"финальная\s+проверка",
        r"\[STATE\]\s+последняя\s+строка",
        r"\[APPEARANCE\]\s+до\s+\[STATE\]",
        r"\[NPC:\s*[^\]]*\]\s+до\s+\[STATE\]",
        r"скрытый\s+опыт",
        r"не\s+совмещай\s+level_up",
        # Служебные секции, которые модель может вывалить целиком
        r"^===\s.*===$",
        r"^\s*[1-7]️⃣\s",
        r"^\s*\d+\.\s+\*\[[^\]]*\]\s*$",
        # Внутренние рассуждения модели, утёкшие в ответ (reasoning-style)
        r"посмотрим на контекст прошлых сообщений",
        r"в предоставленном броске",
        r"если мы интерпретируем",
        r"обычно игрок должен",
        r"он говорит, что это бросок",
        r"в запросе было",
        r"но по инструкции",
        r"я не должен бросать",
        r"я не должен\b.*кубик",
        r"^мы находимся в",
    ]
    # Собираем один regex: case-insensitive
    combined = _re.compile("|".join(leak_patterns), _re.IGNORECASE | _re.MULTILINE)

    lines = reply.split("\n")
    kept = []
    for ln in lines:
        if combined.search(ln):
            continue
        kept.append(ln)
    return "\n".join(kept).strip()
