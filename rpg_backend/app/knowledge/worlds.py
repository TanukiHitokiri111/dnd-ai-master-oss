class FlowWalkMechanics:
    """Чистая механика перемещения между мирами."""

    @staticmethod
    def can_travel(
        current_world: str,
        target_world: str,
        character_level: int,
        has_material: bool = True,
    ) -> tuple[bool, str]:
        """Проверить возможность перемещения. Returns: (можно, причина/детали)."""
        current = WORLD_TEMPLATES.get(current_world)
        target = WORLD_TEMPLATES.get(target_world)

        if not current:
            return False, f"Мир «{current_world}» не найден."
        if not target:
            return False, f"Мир «{target_world}» не найден."
        if current.key == target.key:
            return False, "Вы уже здесь."
        if not has_material:
            return False, (
                f"Нужен предмет из {target.name}. "
                "Найдите или создайте что-то из этого мира."
            )

        tier_diff = target.tier - current.tier

        # Вниз — всегда
        if tier_diff <= 0:
            return True, ""

        # Вверх — проверка по величине скачка
        if tier_diff <= 1.0:
            if character_level < 9:
                return False, "Flow Walk требует 9-й уровень (5-й круг заклинаний)."
            return True, "СЛ Аркана = 15"
        elif tier_diff <= 2.0:
            if character_level < 13:
                return False, "Скачок >1.0 тира требует 13-й уровень."
            return True, "СЛ Аркана = 20"
        else:
            if character_level < 17:
                return False, "Скачок >2.0 тира требует 17-й уровень."
            return True, "СЛ Аркана = 25 (внимание высших сущностей)"

    @staticmethod
    def list_reachable(current_world: str, character_level: int) -> list[dict]:
        """Список миров, доступных для перемещения."""
        current = WORLD_TEMPLATES.get(current_world)
        if not current:
            return []

        reachable = []
        for key, world in WORLD_TEMPLATES.items():
            if key == current.key:
                continue
            ok, detail = FlowWalkMechanics.can_travel(
                current_world, key, character_level
            )
            reachable.append({
                "key": key,
                "name": world.name,
                "tier": world.tier,
                "tier_name": flow_tier_name(world.tier),
                "direction": "⬆ вверх" if world.tier > current.tier else "⬇ вниз",
                "tier_diff": round(world.tier - current.tier, 1),
                "can_travel": ok,
                "detail": detail if not ok else (detail or "Доступен"),
            })

        reachable.sort(key=lambda w: (not w["can_travel"], -w["tier"]))
        return reachable

    @staticmethod
    def get_world_context(world_key: str) -> dict:
        """Контекст мира для system prompt DM."""
        world = WORLD_TEMPLATES.get(world_key)
        if not world:
            return {"error": f"Мир «{world_key}» не найден."}
        return {
            "key": world.key,
            "name": world.name,
            "tier": world.tier,
            "tier_name": flow_tier_name(world.tier),
            "magic_density": world.magic_density,
            "tech_level": world.tech_level,
            "genre": world.genre,
            "prompt": world.to_prompt(),
            "rules": world.rules_overrides,
        }


