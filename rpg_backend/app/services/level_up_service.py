def validate_multiclass(stats: dict[str, int], new_class: str) -> tuple[bool, str | None]:
    """
    Проверить, может ли персонаж взять мультикласс.
    
    stats: {"str": 15, "dex": 12, ...} — текущие статы персонажа
    new_class: название класса (рус.)
    
    Returns (ok, error_message)
    """
    # Точный ключ приоритетнее .title(): суффиксированные ключи миров
    # («Солдат__nuclear_wasteland») .title() искажает → "Невозможно взять"
    reqs = MULTICLASS_REQUIREMENTS.get(new_class)
    if reqs is None:
        reqs = MULTICLASS_REQUIREMENTS.get(new_class.title())
    if reqs is None:
        return False, f"Неизвестный класс для мультикласса: {new_class}"
    
    # Формат: dict = все статы обязательны (AND), list[dict] = хотя бы одна группа (OR)
    if isinstance(reqs, list):
        # OR: хотя бы одна группа требований должна выполняться
        for group in reqs:
            if all(stats.get(stat, 0) >= val for stat, val in group.items()):
                return True, None
        # Ни одна группа не прошла — сообщаем про все
        groups_desc = " ИЛИ ".join(
            " + ".join(f"{stat.upper()}≥{val}" for stat, val in g.items())
            for g in reqs
        )
        return False, f"Для мультикласса в {new_class} нужно: {groups_desc}"
    else:
        # AND: все статы должны быть >= требуемых
        for stat, required in reqs.items():
            current = stats.get(stat, 0)
            if current < required:
                return False, f"Для мультикласса в {new_class} нужно {stat.upper()} ≥ {required}, у вас {current}"
    
    return True, None


def get_caster_type(class_name: str, subclass: str | None = None) -> str:
    """Определить тип заклинателя. Учитывает подкласс для треть-кастеров."""
    name = class_name.title()
    if name in FULL_CASTERS:
        return "full"
    if name in ARTIFICER_CASTER:
        return "artificer"  # Артефактор: half-кастер с округлением вверх
    if name in HALF_CASTERS:
        return "half"
    # Треть-кастеры (Eldritch Knight, Arcane Trickster) — через подкласс
    if subclass and name in THIRD_CASTER_SUBCLASSES and THIRD_CASTER_SUBCLASSES[name] in subclass:
        return "third"
    return "none"


def compute_multiclass_caster_level(classes: list[tuple[str, int]], subclasses: dict[str, str] | None = None) -> int:
    """
    Вычислить эффективный уровень заклинателя для мультикласса.
    
    classes: [("Волшебник", 3), ("Жрец", 2)] → caster_level = 3 + 2 = 5
    subclasses: {"Воин": "Мистический рыцарь", ...} для треть-кастеров
    
    Правила D&D 2024:
    - Полные кастеры (full): уровень класса идёт 1:1
    - Половинистые (half): уровень / 2 (округление вниз)
    - Треть-кастеры (third): уровень / 3 (округление вниз); только через подкласс
    - Не-кастеры (none): 0
    
    Warlock (Колдун) исключён из мультикаста — его Pact Magic отдельная.
    """
    subclasses = subclasses or {}
    caster_level = 0
    for class_name, level in classes:
        if class_name.title() == "Колдун":
            continue  # Pact Magic — отдельно
        subclass = subclasses.get(class_name.title())
        ctype = get_caster_type(class_name, subclass)
        progression = CASTER_PROGRESSION.get(ctype, lambda _: 0)
        caster_level += progression(level)
    return max(0, caster_level)


def compute_spell_slots(classes: list[tuple[str, int]], subclasses: dict[str, str] | None = None) -> dict[str, int] | None:
    """
    Вычислить слоты заклинаний мультикастового заклинателя.
    
    subclasses: {"Воин": "Мистический рыцарь"} для учёта треть-кастеров.
    Возвращает None если персонаж вообще не заклинатель.
    Отдельно обрабатывает Колдуна (Pact Magic) — не смешивается с обычными слотами.
    """
    subclasses = subclasses or {}
    # Проверяем Колдуна отдельно — Pact Magic не смешивается
    warlock_level = _get_class_level(classes, "Колдун")
    if warlock_level > 0:
        pact_slots = _warlock_pact_slots(warlock_level)
        other_classes = [(c, l) for c, l in classes if c.title() != "Колдун"]
        if other_classes:
            other_slots = _compute_regular_slots(other_classes, subclasses)
            if other_slots:
                return {**other_slots, **pact_slots}
            return pact_slots
        return pact_slots
    
    return _compute_regular_slots(classes, subclasses)


def _compute_regular_slots(classes: list[tuple[str, int]], subclasses: dict[str, str]) -> dict[str, int] | None:
    """Обычные слоты (не Pact Magic)."""
    caster_level = compute_multiclass_caster_level(classes, subclasses)
    if caster_level == 0:
        return None
    slots = MULTICLASS_SPELL_SLOTS.get(caster_level, MULTICLASS_SPELL_SLOTS.get(20, {}))
    return {str(slot_level): count for slot_level, count in slots.items()}


def _warlock_pact_slots(wl_level: int) -> dict[str, int]:
    """Слоты Pact Magic Колдуна: всегда максимального круга, восстанавливаются за короткий отдых."""
    pact_circle = min(5, (wl_level + 1) // 2)
    if wl_level <= 1:
        count = 1
    elif wl_level <= 10:
        count = 2
    elif wl_level <= 16:
        count = 3
    else:
        count = 4
    return {f"pact_{pact_circle}": count}


def _get_class_level(classes: list[tuple[str, int]], class_name: str) -> int:
    """Получить уровень конкретного класса."""
    for cn, lvl in classes:
        if cn.title() == class_name.title():
            return lvl
    return 0


