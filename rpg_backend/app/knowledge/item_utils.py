def _build_full_rus_map() -> dict[str, str]:
    """Обратный маппинг русских названий → ключи каталога.

    Автоген из ВСЕГО каталога (ITEM_CATALOG + EXTRA_ITEM_CATALOG):
    русское name из записи → латинский ключ. Это чинит
    «[BREAK: рапира] не ломает rapier» — раньше RUS-маппинг содержал
    только стартовое снаряжение классов, и русское название оружия
    из каталога не резолвилось в ключ.
    """
    from app.knowledge.srd_rules import ITEM_CATALOG

    mapping: dict[str, str] = {}

    def _add(name: str, key: str) -> None:
        mapping.setdefault(name.strip().lower(), key)

    for key, cat in ITEM_CATALOG.items():
        name = (cat.get("name") or "").strip()
        if not name:
            continue
        _add(name, key)
        # «Зелье лечения (2d4+2 ПЗ)» → «зелье лечения»
        base = name.split("(")[0].strip()
        if base and base.lower() != name.lower():
            _add(base, key)
    for key, cat in EXTRA_ITEM_CATALOG.items():
        name = (cat.get("name") or "").strip()
        if not name:
            continue
        _add(name, key)
        base = name.split("(")[0].strip()
        if base and base.lower() != name.lower():
            _add(base, key)

    # Распространённые синонимы (обратный порядок слов и сокращения)
    _synonyms: dict[str, str] = {
        "лук длинный": "longbow",
        "лук короткий": "shortbow",
        "меч длинный": "longsword",
        "меч короткий": "shortsword",
        "меч двуручный": "greatsword",
        "арбалет лёгкий": "light_crossbow",
        "арбалет тяжёлый": "heavy_crossbow",
        "зелье исцеления": "potion_healing",
        "зелье лечения": "potion_healing",
        "potion of healing": "potion_healing",
        "potion_of_healing": "potion_healing",
        "аптечка": "healers_kit",
        "набор лекаря": "healers_kit",
        "инструменты воровские": "thieves_tools",
        "инструменты навигатора": "navigator_tools",
    }
    for syn, key in _synonyms.items():
        mapping.setdefault(syn, key)

    return mapping


