def normalize_city(raw: str) -> str:
    """Привести название города из тега к ключу карты. '' если не найден."""
    s = raw.strip().lower().replace("ё", "е")
    if s in WORLD_MAP:
        return s
    return WORLD_MAP_ALIASES.get(s, "")


def city_info(city_key: str) -> dict | None:
    """Информация о городе. None если неизвестен."""
    return WORLD_MAP.get(city_key)


def nearest_cities(city_key: str) -> list[dict]:
    """Соседи города: [{key, name, days}]."""
    city = WORLD_MAP.get(city_key)
    if not city:
        return []
    out = []
    for nk, days in city["neighbors"].items():
        n = WORLD_MAP.get(nk, {})
        out.append({"key": nk, "name": n.get("name", nk), "days": days})
    return out
