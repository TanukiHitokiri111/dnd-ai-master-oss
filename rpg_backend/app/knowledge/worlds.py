@dataclass
class WorldTemplate:
    """Шаблон мира. При переходе персонажа в мир, DM получает этот контекст."""
    key: str
    name: str
    tier: float                  # позиция на Потоке (дробная: −3.0 ... +3.0)
    magic_density: float         # множитель магии (1.0 = стандарт D&D)
    tech_level: str              # medieval | steampunk | modern | cyberpunk | divine
    genre: str                   # fantasy | horror | scifi | postapoc | weird
    description: str             # для system prompt DM
    rules_overrides: dict[str, Any] = field(default_factory=dict)

    def to_prompt(self) -> str:
        """Сжать шаблон в кусок system prompt (~300 токенов)."""
        tier_label = flow_tier_name(self.tier)
        infosphere_hint = INFOSPHERE_BY_TIER.get(self.genre, INFOSPHERE_BY_TIER["fantasy"])
        parts = [
            f"## Текущий мир: {self.name}",
            f"Уровень Потока: {self.tier} ({tier_label})",
            f"Плотность магии: {self.magic_density:.1f}x",
            f"Технологии: {self.tech_level}",
            f"Жанр: {self.genre}",
            f"Инфосфера: {infosphere_hint}",
            f"\n{self.description}",
        ]
        if self.rules_overrides:
            parts.append(f"\nОсобые правила: {self.rules_overrides}")
        return "\n".join(parts)


