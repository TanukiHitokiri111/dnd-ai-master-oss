    """
    Получить черты, которые класс даёт на указанном уровне.
    
    new_level — уровень В ЭТОМ КЛАССЕ (не общий уровень персонажа).
    """
    # точный ключ приоритетнее .title(): суффиксированные ключи миров
    # («Пси-навигатор__deep_space») .title() искажает → фолбэк на пустую таблицу
    name = class_name if class_name in FEATURE_TABLES else class_name.title()
    table = FEATURE_TABLES.get(name, {})
    return table.get(new_level, [])


