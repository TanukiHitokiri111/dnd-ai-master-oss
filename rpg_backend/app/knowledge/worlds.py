def world_exclusive_races() -> set[str]:
    """Расы, закреплённые за конкретными мирами (недоступны в стандартных мирах).
    Возвращает union {resolved, plain} (по образцу world_exclusive_classes):
    resolved — суффиксированные внутренние ключи (Гуль__nuclear_wasteland и
    т.п.), plain — простые имена мировых рас. Без plain легаси-ключи
    (Гуль, Киборг, Чистый, Хакер...) протекают в дефолтный листинг /srd/races
    (мир не указан) — мировая раса должна быть доступна только через свой мир.
    Исключение: WORLD_SHARED_BASE_RACE_NAMES — имена, совпадающие с базовыми
    SRD-расами (Человек, Гном, Дварф, ...). Их plain-ключи — базовые расы
    стандартных миров, и они должны оставаться доступны в дефолте
    (исключается только суффиксированный близнец).
    Плюс plain-сокращения из алиасов, чей plain-ключ — НЕ самостоятельная раса
    (дальний космос: «Сигма» — сокращение «Империи Сигмы», её plain-ключ в
    RACIAL_TRAITS добавлен только как алиас-дубликат данных): иначе сокращения
    тоже протекают в дефолтный листинг. plain остаётся доступным в дефолте,
    только если (а) имя входит в мировой список WORLD_RACES (полное имя
    фракции) или (б) у него есть собственный суффиксированный близнец этого же
    мира (Человек__techno_fantasy и т.п.) — тогда plain — настоящая базовая
    раса стандартных миров."""
    result = set()
    for world_key, races in WORLD_RACES.items():
        for r in races:
            result.add(resolve_race_key(world_key, r))
            if r not in WORLD_SHARED_BASE_RACE_NAMES:
                result.add(r)
    from app.knowledge.srd_rules import RACIAL_TRAITS
    for world_key, aliases in WORLD_RACE_ALIASES.items():
        world_races = set(WORLD_RACES.get(world_key, []))
        for ui_name, target in aliases.items():
            if ui_name in RACIAL_TRAITS and (
                ui_name in world_races or f"{ui_name}__{world_key}" in RACIAL_TRAITS
            ):
                continue  # plain — самостоятельная раса (Человек, Гном, Хакер...)
            result.add(ui_name)
    return result


