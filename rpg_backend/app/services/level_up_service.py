def get_simplified_level_up(class_name: str, new_level: int, total_level: int) -> dict:
    """Сводка повышения уровня: черты + авто-ASI + рекомендованные заклинания.
    
    Для уровней 1-5 даёт короткую нарративную сводку вместо механик.
    """
    name = class_name.title()
    features = FEATURE_TABLES.get(name, {}).get(new_level, [])
    
    result = {
        "level": new_level,
        "total_level": total_level,
        "features": features,
        "asi": None,
        "spells": [],
    }
    
    # Авто-ASI на уровнях класса 4 (per-class, не total_level)
    if new_level in {4}:
        stat = AUTO_ASI.get(name, "str")
        stat_names = {"str": "Силы", "dex": "Ловкости", "con": "Телосложения",
                      "int": "Интеллекта", "wis": "Мудрости", "cha": "Харизмы"}
        result["asi"] = {"stat": stat, "bonus": 2, "label": stat_names.get(stat, stat)}
    
    # Рекомендованные заклинания для кастеров
    if name in AUTO_SPELLS and new_level in AUTO_SPELLS[name]:
        result["spells"] = AUTO_SPELLS[name][new_level]
    
    return result


def get_hit_points(hit_die: int, hp_roll: int | None = None) -> int:
    """
    Вычислить полученные хиты при повышении уровня.
    
    Если hp_roll не указан — берём среднее (округление вверх, как в 2014 PHB).
    """
    if hp_roll is not None:
        return max(1, hp_roll)  # минимум 1 HP
    # Среднее: d6→4, d8→5, d10→6, d12→7
    return (hit_die // 2) + 1


def apply_stat_increase(
    stats: dict[str, int],
    increases: dict[str, int],
) -> dict[str, int]:
    """
    Применить повышение статов. Не даёт превысить 20 (до модификаторов
    и магических предметов — это базовый лимит).
    """
    result = dict(stats)
    for stat, bonus in increases.items():
        # Нормализуем имя
        key = STAT_MAP.get(stat.lower(), stat)
        if key not in result:
            result[key] = 0
        result[key] = min(20, result[key] + bonus)
    return result
